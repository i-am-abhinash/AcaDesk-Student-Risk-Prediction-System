import smtplib
from email.mime.text import MIMEText
from email.mime.multipart import MIMEMultipart

class EmailService:
    def __init__(self):
        # We use the explicitly provided credentials by the user
        self.smtp_server = "smtp.gmail.com"
        self.smtp_port = 587
        self.sender_email = "gowriabhinash1919@gmail.com"
        self.sender_password = "NAAKU TELIDHU19"

    def send_early_warning_alert(self, to_emails, student_name, student_id, college_name, risk_level, dominant_factor):
        """
        Sends an automated HTML email to the provided addresses (student and parent).
        """
        if not to_emails:
            print("No email addresses provided for alert.")
            return False

        subject = f"⚠️ URGENT: Academic Early Warning Alert for {student_name}"
        
        html_content = f"""
        <html>
            <body style="font-family: Arial, sans-serif; color: #333;">
                <div style="max-width: 600px; margin: 0 auto; border: 1px solid #ddd; padding: 20px; border-radius: 8px;">
                    <h2 style="color: #E53935; text-align: center;">Academic Early Warning Alert</h2>
                    <p>Dear Student / Parent,</p>
                    <p>This is an automated notification from the <b>AcaDesk AI Monitoring System</b> at {college_name}.</p>
                    
                    <p>We are writing to inform you that the academic risk profile for <b>{student_name} ({student_id})</b> has recently changed to: 
                    <strong style="color: #E53935;">{risk_level} Risk</strong>.</p>
                    
                    <div style="background-color: #fce4e4; padding: 15px; border-left: 5px solid #E53935; margin: 20px 0;">
                        <p style="margin: 0;"><b>Primary Area of Concern:</b> {dominant_factor}</p>
                    </div>
                    
                    <p>Our predictive systems indicate that without immediate intervention, there is a significant risk to the student's degree progression or academic standing.</p>
                    
                    <p><b>Required Action:</b></p>
                    <ul>
                        <li>Please contact your assigned Faculty Mentor or the Head of Department immediately.</li>
                        <li>Log into the student portal to review current attendance and academic standings.</li>
                    </ul>
                    
                    <p>Early intervention is the key to student success. We are here to support you!</p>
                    
                    <hr style="border: none; border-top: 1px solid #eee; margin: 20px 0;">
                    <p style="font-size: 12px; color: #888; text-align: center;">
                        This is an automated message generated by the AcaDesk Intervention Engine. Please do not reply directly to this email.
                    </p>
                </div>
            </body>
        </html>
        """

        try:
            msg = MIMEMultipart("alternative")
            msg["Subject"] = subject
            msg["From"] = f"AcaDesk Alerts <{self.sender_email}>"
            
            # If to_emails is a list, join it. Otherwise, use it directly.
            if isinstance(to_emails, list):
                # Filter out empty or None emails
                to_emails = [e for e in to_emails if e]
                if not to_emails:
                    return False
                msg["To"] = ", ".join(to_emails)
            else:
                msg["To"] = to_emails

            part = MIMEText(html_content, "html")
            msg.attach(part)

            # Create secure connection with server and send email
            server = smtplib.SMTP(self.smtp_server, self.smtp_port)
            server.starttls()
            server.login(self.sender_email, self.sender_password)
            server.sendmail(self.sender_email, to_emails, msg.as_string())
            server.quit()
            
            print(f"Successfully sent early warning email to {msg['To']}")
            return True
        except Exception as e:
            print(f"Failed to send email: {e}")
            return False
