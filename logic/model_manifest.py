import os
import json
import logging
from typing import Optional, List

_log = logging.getLogger(__name__)

def get_model_required_features() -> Optional[List[str]]:
    """
    Reads the sidecar JSON files generated by the training scripts to determine
    the combined list of feature column names required by the active models.
    Returns None if no manifest is found (fallback to all fields).
    """
    base_dir = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    expanded_path = os.path.join(base_dir, 'synapse_model.features.json')
    first_year_path = os.path.join(base_dir, 'first_year_model.features.json')
    
    features = set()
    found_any = False
    
    if os.path.exists(expanded_path):
        try:
            with open(expanded_path, 'r') as f:
                features.update(json.load(f))
                found_any = True
        except Exception as e:
            _log.warning(f"Failed to read {expanded_path}: {e}")
            
    if os.path.exists(first_year_path):
        try:
            with open(first_year_path, 'r') as f:
                features.update(json.load(f))
                found_any = True
        except Exception as e:
            _log.warning(f"Failed to read {first_year_path}: {e}")
            
    if found_any:
        return list(features)
        
    _log.warning("No model feature manifests detected — showing all supported fields.")
    return None
